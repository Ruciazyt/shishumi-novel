/**
 * 根据关键词搜索诗词
 */
export const searchPoetry = (keyword: string): Array<{ category: string; poetry: Poetry }> => {
  const results: Array<{ category: string; poetry: Poetry }> = [];


  for (const [category, poems] of Object.entries(POETRY_CATEGORIES)) {
    for (const poem of poems) {
      if (
        poem.title.includes(keyword) ||
        poem.author.includes(keyword) ||
        poem.content.some(line => line.includes(keyword)) ||
        (poem.interpretation && poem.interpretation.includes(keyword))
      ) {
        results.push({ category, poetry: poem });
      }
    }
  }

  return results;
};
